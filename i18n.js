    function raw(locale, path) {
        const chosen = translations[locale] || translations["en-US"];
        const fallback = translations["en-US"];
        const parts = String(path).split(".");

        const read = source => {
            let value = source;
            for (const part of parts) {
                if (value == null || typeof value !== "object" || !(part in value)) return undefined;
                value = value[part];
            }
            return value;
        };

        const localized = read(chosen);
        return localized === undefined ? read(fallback) : localized;
    }

    function format(value, params = {}) {
        if (typeof value !== "string") return value;
        return value.replace(/\{(\w+)\}/g, (_, key) => String(params[key] ?? `{${key}}`));
    }

    function t(locale, path, params = {}) {
        const value = raw(locale, path);
        return typeof value === "string" ? format(value, params) : value;
    }

    function normalizeLocale(value) {
        const candidate = String(value || "").replace("_", "-");
        const exact = supported.find(code => code.toLowerCase() === candidate.toLowerCase());
        if (exact) return exact;

        const lower = candidate.toLowerCase();
        if (lower.startsWith("en-gb")) return "en-GB";
        if (lower.startsWith("en")) return "en-US";
        if (lower.startsWith("ru")) return "ru-RU";
        if (lower.startsWith("lv")) return "lv-LV";
        if (lower.startsWith("es")) return "es-ES";
        if (lower.startsWith("pt")) return "pt-BR";
        if (lower.startsWith("de")) return "de-DE";
        if (lower.startsWith("fr")) return "fr-FR";
        if (lower.startsWith("pl")) return "pl-PL";
        return "en-US";
    }

    function detectLocale() {
        const candidates = Array.isArray(navigator.languages) && navigator.languages.length
            ? navigator.languages
            : [navigator.language || "en-US"];

        for (const candidate of candidates) {
            const normalized = normalizeLocale(candidate);
            if (normalized !== "en-US" || String(candidate).toLowerCase().startsWith("en")) return normalized;
        }
        return "en-US";
    }

